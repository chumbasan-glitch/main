/* ================= 文章題の場面をふやす（上書き） =================
   それぞれの文章題に、数量の関係は同じで場面のちがう問題を用意する */
function override(ref, gen){ const s = findSub(ref); s.gen = gen; }
/* 場面は、1まいのプリントの中でなるべく同じものが続かないよう、まだ使っていない場面から選ぶ */
const SCENE_USE = new Map();
const scene = list => {
  const keys = list.map(f => f.toString()), us = keys.map(k => SCENE_USE.get(k) || 0), m = Math.min(...us);
  const i = pick(list.map((f, j) => j).filter(j => us[j] === m));
  SCENE_USE.set(keys[i], m + 1);
  return list[i]();
};

